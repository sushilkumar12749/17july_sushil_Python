# ) Write a Python program to read a string, an integer, and a float from the keyboard and display them.

# Read a string, an integer, and a float from the user
string_input = input("Enter a string: ")
integer_input = int(input("Enter an integer: "))
float_input = float(input("Enter a float: "))

# Display the values
print("You entered:")
print(f"String: {string_input}")
print(f"Integer: {integer_input}")
print(f"Float: {float_input}")